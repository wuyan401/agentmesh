/**
 * DeepSeek Harness adapter.
 *
 * Injection is a `--patch` overlay that appends the hub MCP server to *this
 * spawned process only*. The shared profile is never touched, which is what keeps
 * the platform incapable of reaching into a D-Session (C3) — there is no shared
 * file that a P-Session could edit to influence a directly-launched CLI.
 */

import fs from 'node:fs'
import path from 'node:path'
import { buildChildEnv, hubMcpServerPath, quote } from './types.ts'
import type { Adapter, SpawnContext, SpawnPlan } from './types.ts'

export function dshPatchYaml(ctx: SpawnContext): string {
  const server = hubMcpServerPath()
  const root = ctx.hub.paths.root
  const lines: string[] = []
  lines.push('# Generated by AgentMesh for one spawned P-Session. Do not edit.')
  lines.push('- insert:')
  lines.push('    - id: agentmesh-hub-mcp')
  lines.push('      name: "@deepseek-ai/dsh-mcp-client"')
  lines.push('      config:')
  lines.push('        transport: stdio')
  lines.push('        serverName: hub')
  lines.push(`        command: ${quote(process.execPath.replace(/\\/g, '/'))}`)
  lines.push('        args:')
  lines.push(`          - ${quote(server.replace(/\\/g, '/'))}`)
  lines.push(`          - ${quote('--root')}`)
  lines.push(`          - ${quote(root.replace(/\\/g, '/'))}`)
  lines.push(`          - ${quote('--session')}`)
  lines.push(`          - ${quote(ctx.session.session_id)}`)
  lines.push('        env:')
  lines.push(`          MESH_ROOT: ${quote(root.replace(/\\/g, '/'))}`)
  lines.push(`          MESH_SESSION_ID: ${quote(ctx.session.session_id)}`)
  lines.push(`          MESH_AGENT_ID: ${quote(ctx.agent.agent_id)}`)
  lines.push('        toolCallTimeoutMs: 60000')
  lines.push('        failOnStartupError: true')
  return `${lines.join('\n')}\n`
}

export const dshAdapter: Adapter = {
  name: 'dsh',
  build(ctx: SpawnContext): SpawnPlan {
    const patchFile = path.join(ctx.scratch, 'dsh-hub.patch.yml')
    fs.mkdirSync(ctx.scratch, { recursive: true })
    fs.writeFileSync(patchFile, dshPatchYaml(ctx))

    const args = [...ctx.agent.args, '--patch', patchFile, ...ctx.agent.headless_args]
    if (ctx.agent.prompt_mode === 'arg') {
      if (ctx.agent.prompt_flag) args.push(ctx.agent.prompt_flag, ctx.prompt)
      else args.push(ctx.prompt)
    }
    const plan: SpawnPlan = {
      command: ctx.agent.command,
      args,
      cwd: ctx.worktree,
      env: buildChildEnv(ctx),
      artifacts: [patchFile],
      injection: `MCP server "hub" appended via --patch ${path.basename(patchFile)} (profile untouched)`,
    }
    if (ctx.agent.prompt_mode === 'stdin') plan.stdin = ctx.prompt
    return plan
  },
}

/** The tool prefix DSH gives MCP tools (`mcp__<serverName>__`). */
export const DSH_TOOL_PREFIX = 'mcp__hub__'
